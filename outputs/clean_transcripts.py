# 3. CLEAN ALL TRANSCRIPTS
print("\n CLEANING TRANSCRIPTS...")
input_root, output_root = "transcripts_raw", "transcripts_cleaned"
txt_files = glob.glob(os.path.join(input_root, "**", "*.txt"), recursive=True)

for in_path in txt_files:
    rel_path = os.path.relpath(in_path, input_root)
    out_path = os.path.join(output_root, rel_path)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)

    with open(in_path, "r", encoding="utf-8", errors="ignore") as f:
        lines = f.readlines()
    cleaned = [clean_line(l) for l in lines if clean_line(l)]

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(cleaned))

cleaned_files = glob.glob(os.path.join(output_root, "**", "*.txt"), recursive=True)

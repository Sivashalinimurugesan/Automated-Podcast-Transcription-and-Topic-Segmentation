# 1. CLEANING FUNCTION (ENHANCED)
def clean_line(line: str) -> str:
    patterns_to_drop = [
        r"^\s*Transcript generated by", r"^\s*Powered by .*",
        r"^\s*\d{1,2}:\d{2}(:\d{2})?\s*$", r"^\s*Time\s*Stamp.*$",
        r"^\s*\[[0-9:]+\]\s*$", r"^\s*\(\d+\)\s*$"
    ]
    for pat in patterns_to_drop:
        if re.search(pat, line, re.IGNORECASE): return ""
    line = re.sub(r"^\s*(Speaker|Person|User|Assistant)\s*\d*\s*[:\-]?\s*", "", line, re.IGNORECASE)
    line = re.sub(r"[^\w\s\.\,\!\?\:\;\-\'\"]", " ", line)
    line = re.sub(r"\s+", " ", line.strip())
    return line if len(line) > 3 else ""

